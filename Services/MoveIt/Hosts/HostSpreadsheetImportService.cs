using System.Text.RegularExpressions;
using Microsoft.Extensions.Caching.Memory;
using Microsoft.Extensions.Options;
using MoveItAutomationUI.Models;
using MoveItAutomationUI.Services.Metadata;

namespace MoveItAutomationUI.Services.MoveIt.Hosts;

public sealed record HostImportIssue(int? RowNumber, string Column, string Severity, string Message);
public sealed record HostImportRow(int RowNumber, string Status, IReadOnlyDictionary<string, string> Values, IReadOnlyList<HostImportIssue> Issues);
public sealed record HostImportAnalysis(string AnalysisId, IReadOnlyList<string> Columns, IReadOnlyList<HostImportRow> Rows,
    IReadOnlyList<HostImportIssue> Issues, int ValidRows, int SkippedRows, int ErrorRows);
public sealed record HostImportOutcome(int RowNumber, string Name, string Outcome, string HostId, string Message);

public interface IHostSpreadsheetImportService
{
    HostImportAnalysis Preview(byte[] bytes, string fileName);
    Task<HostImportAnalysis> AnalyzeAsync(byte[] bytes, string fileName, string prefix, bool updateExisting, bool testAfterCreation, CancellationToken cancellationToken);
    Task<HostImportOutcome> ImportRowAsync(string analysisId, int rowNumber, CancellationToken cancellationToken);
    void Finish(string analysisId);
}

// Sensitive cells never leave the server. The parsed CSV/XLSX exists only inside a short-lived,
// session-scoped in-memory analysis; clients get redacted previews and import status only.
public sealed class HostSpreadsheetImportService : IHostSpreadsheetImportService
{
    private static readonly HashSet<string> CoreColumns = new(StringComparer.OrdinalIgnoreCase)
    { "NAME", "HOST_TYPE", "HOST", "PORT", "USERNAME", "PASSWORD", "SSHKEY", "SECURE", "UNC", "DESCRIPTION", "RESOURCE_GROUP", "IGNORE_CERT_PROBS", "SCRIPT_PATH", "FROM_ADDRESS", "BUCKET", "CONTAINER", "DATA_INTEGRITY",
      "TENANT_NAME", "SITE", "SITE_URL_PREFIX", "CLIENT_ID", "TENANT_ID",
      "DOCUMENT_LIBRARY", "DOCUMENT_LIBRARY_GUID", "CERT_STORE", "CERT_SUBJECT", "CERT_SHA1" };
    private static bool IsSensitiveColumn(string header)
        => header.Equals("PASSWORD", StringComparison.OrdinalIgnoreCase)
            || header.EndsWith("_PASSWORD", StringComparison.OrdinalIgnoreCase)
            || header.Contains("SECRET", StringComparison.OrdinalIgnoreCase)
            || header.EndsWith("_TOKEN", StringComparison.OrdinalIgnoreCase);
    private static readonly TimeSpan Lifetime = TimeSpan.FromMinutes(15);
    private readonly IMemoryCache _cache;
    private readonly IMoveItSessionService _sessions;
    private readonly IAutomationHostService _hosts;
    private readonly IMoveItRestClient _rest;
    private readonly IResourceGroupLookupService _groups;
    private readonly IMetadataValueValidationService _metadataValidation;
    private readonly IMetadataRepository _metadata;
    private readonly IHostConnectionTestService _connectionTests;
    private readonly IHostHealthService _hostHealth;
    private readonly IHostUndoService _undo;
    private readonly MetadataUiOptions _metadataOptions;

    private sealed record Plan(string Name, HostBasicDefinition? Create, HostBasicUpdate? Update,
        string ExistingHostId, IReadOnlyDictionary<string, string> Metadata);
    private sealed class AnalysisState
    {
        public required string Username { get; init; }
        public required string EnvironmentKey { get; init; }
        public required Dictionary<int, Plan> Plans { get; init; }
        public bool TestAfterCreation { get; init; }
        public bool UpdateExisting { get; init; }
        public HashSet<int> ConsumedRows { get; } = new();
        public object Sync { get; } = new();
    }

    public HostSpreadsheetImportService(IMemoryCache cache, IMoveItSessionService sessions,
        IAutomationHostService hosts, IMoveItRestClient rest, IResourceGroupLookupService groups,
        IMetadataValueValidationService metadataValidation, IMetadataRepository metadata,
        IHostConnectionTestService connectionTests, IHostHealthService hostHealth, IHostUndoService undo,
        IOptionsSnapshot<MetadataUiOptions> metadataOptions)
    {
        _cache = cache; _sessions = sessions; _hosts = hosts; _rest = rest; _groups = groups;
        _metadataValidation = metadataValidation; _metadata = metadata;
        _connectionTests = connectionTests; _hostHealth = hostHealth; _undo = undo; _metadataOptions = metadataOptions.Value;
    }

    // Keep spreadsheet headers aligned with Task Import while recognizing files generated by
    // the original Phase 1 template. Normalize both columns and row dictionaries before any
    // validation or browser preview; the shared Task Import reader is intentionally unchanged.
    internal static TaskSpreadsheetFileData ReadHostFile(byte[] bytes, string fileName)
    {
        var file = TaskSpreadsheetImportFileReader.Read(bytes, fileName, preservePasswordCells: true);
        static string Canonical(string header) => header switch
        {
            "HOSTTYPE" => "HOST_TYPE",
            "RESOURCEGROUP" => "RESOURCE_GROUP",
            "IGNORECERTPROBS" => "IGNORE_CERT_PROBS",
            _ => header
        };
        var headers = file.Headers.Select(Canonical).ToArray();
        var duplicates = headers.GroupBy(header => header, StringComparer.OrdinalIgnoreCase)
            .Where(group => group.Count() > 1).Select(group => group.Key).ToArray();
        if (duplicates.Length > 0)
            throw new InvalidOperationException("Duplicate Host import columns after normalization: " + string.Join(", ", duplicates) + ".");
        var rows = file.Rows.Select(row => new TaskSpreadsheetRawRow(row.RowNumber,
            row.Values.ToDictionary(pair => Canonical(pair.Key), pair => pair.Value,
                StringComparer.OrdinalIgnoreCase))).ToArray();
        return new TaskSpreadsheetFileData(headers, rows, file.SkippedBlankRows);
    }

    public HostImportAnalysis Preview(byte[] bytes, string fileName)
    {
        var file = ReadHostFile(bytes, fileName);
        var visible = file.Rows.Select(row => new HostImportRow(row.RowNumber, "Pending", Redact(row.Values), Array.Empty<HostImportIssue>())).ToArray();
        return new HostImportAnalysis(string.Empty, file.Headers, visible, Array.Empty<HostImportIssue>(), 0, 0, 0);
    }

    public async Task<HostImportAnalysis> AnalyzeAsync(byte[] bytes, string fileName, string prefix, bool updateExisting, bool testAfterCreation, CancellationToken cancellationToken)
    {
        var session = _sessions.Get() ?? throw new MoveItAuthenticationException("MOVEit session expired. Please sign in again.");
        var file = ReadHostFile(bytes, fileName);
        var headers = file.Headers.ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (!headers.Contains("NAME") || !headers.Contains("HOST_TYPE"))
            throw new InvalidOperationException("The spreadsheet must contain NAME and HOST_TYPE columns.");
        var metadataGroups = (_metadataOptions.Hosts.Fields ?? new List<MetadataFieldDefinition>())
            .Where(field => !string.IsNullOrWhiteSpace(field.Name))
            .GroupBy(field => Normalize(field.Name), StringComparer.OrdinalIgnoreCase)
            .ToArray();
        if (metadataGroups.Any(group => group.Count() != 1 || group.Key.Length == 0))
            throw new InvalidOperationException("Host metadata field names are ambiguous after spreadsheet normalization.");
        var fields = metadataGroups.ToDictionary(group => "METADATA_" + group.Key,
            group => group.First(), StringComparer.OrdinalIgnoreCase);
        // Blank optional metadata columns in the downloadable template must not block an
        // installation where that custom MAUI metadata field has not been configured.
        // Nonblank unconfigured metadata is rejected instead of being silently discarded.
        var unknown = file.Headers.Where(column => !CoreColumns.Contains(column) && !fields.ContainsKey(column)
            && !(column.StartsWith("METADATA_", StringComparison.OrdinalIgnoreCase)
                 && file.Rows.All(row => !row.Values.TryGetValue(column, out var value) || string.IsNullOrWhiteSpace(value)))).ToArray();
        if (unknown.Length > 0) throw new InvalidOperationException("Unrecognized Host import columns: " + string.Join(", ", unknown) + ".");
        if (prefix.Length > 60) throw new InvalidOperationException("Host Name Prefix cannot exceed 60 characters.");

        var existing = (await _hosts.GetHostSnapshotAsync(true, cancellationToken)).Hosts
            .GroupBy(host => host.Name, StringComparer.OrdinalIgnoreCase)
            .ToDictionary(group => group.Key, group => group.ToArray(), StringComparer.OrdinalIgnoreCase);
        var groups = await _groups.GetVisibleNamesAsync(cancellationToken);
        var keys = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var planned = new Dictionary<int, Plan>();
        var rows = new List<HostImportRow>();
        var allIssues = new List<HostImportIssue>();
        int valid = 0, skipped = 0, errors = 0;
        foreach (var row in file.Rows)
        {
            var issues = new List<HostImportIssue>();
            string status;
            try
            {
                var name = (prefix + (row.Values.TryGetValue("NAME", out var rawName) ? rawName.Trim() : string.Empty)).Trim();
                var matches = existing.TryGetValue(name, out var candidates) ? candidates : Array.Empty<AutomationHost>();
                var target = matches.Length == 1 ? matches[0] : null;
                // A create-only import must skip an existing Host regardless of
                // unrelated connection fields in that spreadsheet row. Do not
                // resolve SSH keys, validate credentials or write metadata for
                // an object we will not modify.
                if (target is not null && !updateExisting)
                {
                    if (!keys.Add(name))
                    {
                        status = "Error";
                        issues.Add(new HostImportIssue(row.RowNumber, "NAME", "Error",
                            "Duplicate Host name in this spreadsheet."));
                        errors++;
                    }
                    else
                    {
                        status = "Skipped";
                        issues.Add(new HostImportIssue(row.RowNumber, "NAME", "Warning",
                            "Host already exists; enable Update existing Host if name already exists to modify it."));
                        skipped++;
                    }
                    rows.Add(new HostImportRow(row.RowNumber, status, Redact(row.Values), issues));
                    allIssues.AddRange(issues);
                    continue;
                }
                HostBasicDefinition? create = null;
                HostBasicUpdate? update = null;
                // Existing update rows do not require credentials that are
                // already securely stored by MOVEit.
                if (target is not null)
                    update = HostBasicDefinitionProfile.ParseUpdate(row.Values, prefix);
                else
                    create = HostBasicDefinitionProfile.Parse(row.Values, prefix);
                var plannedName = update?.Name ?? create!.Name;
                var type = update?.HostType ?? create!.HostType;
                if (testAfterCreation && !_connectionTests.SupportsHostType(type))
                    issues.Add(new HostImportIssue(row.RowNumber, "HOST_TYPE", "Error",
                        "Connection testing is not available for this Host type. Uncheck Test each Host connection before importing."));
                if (!keys.Add(plannedName))
                    issues.Add(new HostImportIssue(row.RowNumber, "NAME", "Error", "Duplicate Host name in this spreadsheet."));
                if (matches.Length > 1)
                    issues.Add(new HostImportIssue(row.RowNumber, "NAME", "Error", "More than one Host matches this name."));
                status = "Valid";
                if (target is not null)
                {
                    if (!target.CanEditDelete)
                        issues.Add(new HostImportIssue(row.RowNumber, "NAME", "Error", "Current MOVEit account cannot edit this Host."));
                    if (!target.TypeCode.Equals(type, StringComparison.OrdinalIgnoreCase))
                        issues.Add(new HostImportIssue(row.RowNumber, "HOST_TYPE", "Error",
                            "Existing Host type differs from the spreadsheet. Host types cannot be converted."));
                    // MOVEit assigns resource groups outside the Host connection XML. Do not
                    // silently ignore group changes; preserve the existing assignment.
                    var groupName = update!.Fields.TryGetValue("RESOURCE_GROUP", out var value) ? value.Trim() : string.Empty;
                    if (groupName.Length > 0 && !groupName.Equals(target.Group.Trim(), StringComparison.OrdinalIgnoreCase))
                        issues.Add(new HostImportIssue(row.RowNumber, "RESOURCE_GROUP", "Error",
                            "Changing Resource Groups is not supported by spreadsheet Host updates. Leave this cell blank to preserve the existing assignment."));
                }
                var keyName = update is null ? create!.SshKeyName
                    : (update.Fields.TryGetValue("SSHKEY", out var sshKey) ? sshKey.Trim() : string.Empty);
                if (keyName.Length > 0 && !await _rest.SshKeyNameExistsAsync(keyName, cancellationToken))
                    issues.Add(new HostImportIssue(row.RowNumber, "SSHKEY", "Error", "SSH client key is not visible to the current MOVEit user."));
                var resourceGroup = update is null ? create!.ResourceGroup
                    : (update.Fields.TryGetValue("RESOURCE_GROUP", out var updateGroup) ? updateGroup.Trim() : string.Empty);
                if (resourceGroup.Length > 0 && !groups.Contains(resourceGroup, StringComparer.OrdinalIgnoreCase))
                    issues.Add(new HostImportIssue(row.RowNumber, "RESOURCE_GROUP", "Error", "Resource Group is not visible to this MOVEit user."));
                var submitted = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                foreach (var field in fields)
                    if (row.Values.TryGetValue(field.Key, out var fieldValue)
                        && (update is null || !string.IsNullOrWhiteSpace(fieldValue)))
                        submitted[field.Value.Name] = fieldValue;
                var metadata = await _metadataValidation.FilterAndValidateAsync(
                    session.GetEnvironmentKey(), _metadataOptions.Hosts, submitted, cancellationToken);
                if (issues.Any(issue => issue.Severity == "Error")) status = "Error";
                if (status == "Valid")
                    planned[row.RowNumber] = new Plan(plannedName, create, update, target?.Id ?? string.Empty, metadata);
            }
            catch (Exception ex) when (ex is ArgumentException or InvalidOperationException)
            {
                status = "Error";
                var column = ex is ArgumentException { ParamName: { Length: > 0 } paramName }
                    ? paramName : "HOST";
                issues.Add(new HostImportIssue(row.RowNumber, column, "Error", ex is ArgumentException
                    ? SafeFieldError(ex.Message) : "Host fields or MAUI metadata could not be validated."));
            }
            if (status == "Valid") valid++;
            else if (status == "Skipped") skipped++;
            else errors++;
            rows.Add(new HostImportRow(row.RowNumber, status, Redact(row.Values), issues));
            allIssues.AddRange(issues);
        }
        var analysisId = Guid.NewGuid().ToString("N");
        _cache.Set(CacheKey(analysisId), new AnalysisState
        {
            Username = session.Username, EnvironmentKey = session.GetEnvironmentKey(), Plans = planned,
            TestAfterCreation = testAfterCreation, UpdateExisting = updateExisting
        }, new MemoryCacheEntryOptions
        {
            SlidingExpiration = Lifetime,
            AbsoluteExpirationRelativeToNow = TimeSpan.FromHours(1)
        });
        return new HostImportAnalysis(analysisId, file.Headers, rows, allIssues, valid, skipped, errors);
    }

    public async Task<HostImportOutcome> ImportRowAsync(string analysisId, int rowNumber, CancellationToken cancellationToken)
    {
        var session = _sessions.Get() ?? throw new MoveItAuthenticationException("MOVEit session expired. Please sign in again.");
        if (!_cache.TryGetValue<AnalysisState>(CacheKey(analysisId), out var state) || state is null
            || !string.Equals(state.Username, session.Username, StringComparison.OrdinalIgnoreCase)
            || !string.Equals(state.EnvironmentKey, session.GetEnvironmentKey(), StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Host import analysis expired. Analyze the spreadsheet again.");
        if (!state.Plans.TryGetValue(rowNumber, out var plan))
            throw new InvalidOperationException("The row is not approved for import.");
        lock (state.Sync)
        {
            if (!state.ConsumedRows.Add(rowNumber)) throw new InvalidOperationException("This Host row has already been submitted.");
        }
        // Consume each row exactly once. Host updates keep the existing MOVEit ID,
        // capture Undo first, and do not consume a license slot.
        string targetId = string.Empty;
        string outcome = string.Empty;
        bool nativeWriteAttempted = false;
        try
        {
            if (plan.Update is not null)
            {
                if (!state.UpdateExisting || plan.ExistingHostId.Length == 0)
                    throw new InvalidOperationException("The analyzed update is no longer authorized.");
                var matches = (await _hosts.GetHostSnapshotAsync(true, cancellationToken)).Hosts
                    .Where(host => host.Name.Equals(plan.Name, StringComparison.OrdinalIgnoreCase)).ToArray();
                if (matches.Length != 1 || !matches[0].Id.Equals(plan.ExistingHostId, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException("The Host identity changed after analysis.");
                var target = matches[0];
                if (!target.CanEditDelete || !target.TypeCode.Equals(plan.Update.HostType, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException("The Host type or edit permission changed after analysis.");
                var groupName = plan.Update.Fields.TryGetValue("RESOURCE_GROUP", out var group) ? group.Trim() : string.Empty;
                if (groupName.Length > 0 && !groupName.Equals(target.Group.Trim(), StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException("The Host Resource Group changed after analysis.");
                targetId = target.Id; // Preserve identity in any indeterminate COM result.
                await _undo.CaptureAsync(target.Id, session.Username, cancellationToken);
                nativeWriteAttempted = true;
                var updated = await _hosts.UpdateConfiguredHostAsync(target.Id, plan.Update, cancellationToken);
                targetId = updated.Id;
                outcome = "Updated";
            }
            else if (plan.Create is not null)
            {
                using var lease = await MoveItLicensePolicy.AcquireHostCreationAsync(session, cancellationToken);
                var hosts = (await _hosts.GetHostSnapshotAsync(true, cancellationToken)).Hosts;
                if (hosts.Any(host => host.Name.Equals(plan.Name, StringComparison.OrdinalIgnoreCase)))
                    return new HostImportOutcome(rowNumber, plan.Name, "Skipped", string.Empty,
                        "Host already exists. Reanalyze before updating.");
                var block = MoveItLicensePolicy.GetHostCapacityBlock(session, hosts.Count, 1);
                if (!string.IsNullOrWhiteSpace(block))
                    return new HostImportOutcome(rowNumber, plan.Name, "Failed", string.Empty, block);
                nativeWriteAttempted = true;
                var created = await _hosts.CreateConfiguredHostAsync(plan.Create, cancellationToken);
                targetId = created.Id;
                outcome = "Created";
            }
            else throw new InvalidOperationException("The analyzed Host import plan is incomplete.");

            // Native Host CRUD has committed. Subsequent metadata and test failures must
            // not misrepresent a committed write as a safe-to-retry failure.
            try
            {
                if (outcome == "Created")
                    await _metadata.RecordObjectCreatedAsync(session.GetEnvironmentKey(), "Host", targetId, session.Username, cancellationToken);
                else
                    await _metadata.RecordObjectConfigurationModifiedAsync(session.GetEnvironmentKey(), "Host", targetId, session.Username, cancellationToken);
                if (plan.Metadata.Count > 0)
                    await _metadata.SaveObjectMetadataAsync(session.GetEnvironmentKey(), "Host", targetId, plan.Metadata, session.Username, cancellationToken);
            }
            catch
            {
                return new HostImportOutcome(rowNumber, plan.Name, "Needs Attention", targetId,
                    $"Host was {outcome.ToLowerInvariant()}, but MAUI metadata/audit could not be saved. Review before retrying.");
            }
            if (state.TestAfterCreation)
            {
                try
                {
                    var test = await _connectionTests.TestHostAsync(targetId, cancellationToken);
                    await _hostHealth.SaveConnectionTestResultAsync(session.GetEnvironmentKey(), test, DateTimeOffset.UtcNow, cancellationToken);
                    if (test.Status.Equals("Passed", StringComparison.OrdinalIgnoreCase))
                        return new HostImportOutcome(rowNumber, plan.Name, outcome, targetId,
                            $"Host {outcome.ToLowerInvariant()}; connection test passed.");
                    return new HostImportOutcome(rowNumber, plan.Name, "Needs Attention", targetId,
                        $"Host was {outcome.ToLowerInvariant()}, but connection test did not pass. Review Host Test results.");
                }
                catch (Exception ex) when (ex is not OperationCanceledException)
                {
                    return new HostImportOutcome(rowNumber, plan.Name, "Needs Attention", targetId,
                        $"Host was {outcome.ToLowerInvariant()}, but connection testing could not complete.");
                }
            }
            return new HostImportOutcome(rowNumber, plan.Name, outcome, targetId,
                $"Host {outcome.ToLowerInvariant()} and verified; connection not tested.");
        }
        catch (HostPartialSaveException ex)
        {
            return new HostImportOutcome(rowNumber, plan.Name, "Needs Attention",
                ex.HostId.Length > 0 ? ex.HostId : targetId,
                "MOVEit accepted the Host write, but verification or checkout release did not complete. Review the Host before retrying.");
        }
        catch (HostNameAlreadyExistsException)
        {
            return new HostImportOutcome(rowNumber, plan.Name, "Skipped", string.Empty,
                "Host already exists. Reanalyze before importing.");
        }
        catch (Exception ex) when (ex is MoveItComException or MoveItApiException or ArgumentException or InvalidOperationException)
        {
            // Before a COM write begins, validation/snapshot failures are known to
            // be unsuccessful. Once a native write is attempted, an exception may
            // mean it committed without a verified response; never invite a blind retry.
            return nativeWriteAttempted
                ? new HostImportOutcome(rowNumber, plan.Name, "Needs Attention", targetId,
                    "MOVEit could not verify this Host import operation. Inspect the Host before any manual retry.")
                : new HostImportOutcome(rowNumber, plan.Name, "Failed", targetId,
                    "Host import did not start. Reanalyze and verify the Host's permissions, type, and current configuration.");
        }
    }

    public void Finish(string analysisId) => _cache.Remove(CacheKey(analysisId));
    private static string CacheKey(string id) => "MAUI:HostImport:" + id;
    private static string Normalize(string name) => Regex.Replace(name.Trim().ToUpperInvariant(), "[^A-Z0-9]+", "_").Trim('_');
    private static IReadOnlyDictionary<string, string> Redact(IReadOnlyDictionary<string, string> values)
        => values.ToDictionary(pair => pair.Key,
            pair => IsSensitiveColumn(pair.Key) && pair.Value.Length > 0 ? "••••••" : pair.Value,
            StringComparer.OrdinalIgnoreCase);
    private static string SafeFieldError(string message)
        => message.StartsWith("Metadata field ", StringComparison.OrdinalIgnoreCase) ? "A Host metadata value is invalid." : message;
}

