using MoveItAutomationUI.Services.MoveIt;

namespace MoveItAutomationUI.Tests.MoveIt;

public sealed class QuickTransferCleanupPolicyTests
{
    private static readonly DateTimeOffset Started = new(2026, 10, 11, 20, 0, 0, TimeSpan.Zero);

    [Fact]
    public void SuccessfulMatchingTaskMayBeDeleted()
    {
        Assert.True(QuickTransferCleanupPolicy.CanDelete(Entry(), Record("Success"), "ADHOC_TEST", false));
    }

    [Theory]
    [InlineData("Failed")]
    [InlineData("No Transfers")]
    [InlineData("Cancelled")]
    public void NonSuccessIsNeverEligible(string status)
    {
        Assert.False(QuickTransferCleanupPolicy.CanDelete(Entry(), Record(status), "ADHOC_TEST", false));
    }

    [Fact]
    public void RunningOrRenamedTaskIsNotEligible()
    {
        Assert.False(QuickTransferCleanupPolicy.CanDelete(Entry(), Record("Success"), "ADHOC_TEST", true));
        Assert.False(QuickTransferCleanupPolicy.CanDelete(Entry(), Record("Success"), "RENAMED", false));
    }

    [Fact]
    public void BackgroundCleanupCredentialsAreRestrictedToOriginalMoveItServer()
    {
        var credentials = new[]
        {
            new DataAccessCredential("secondary", "prod", "Other server", "admin", "secret"),
            new DataAccessCredential("primary", "prod", "Original server", "admin", "secret")
        };

        var original = QuickTransferCleanupWorker.CredentialsForServer(credentials, "PRIMARY");
        var selected = Assert.Single(original);
        Assert.Equal("primary", selected.ServerKey);
        Assert.Empty(QuickTransferCleanupWorker.CredentialsForServer(credentials, "unknown"));
    }

    [Fact]
    public void MismatchedRunIdentityIsNotEligible()
    {
        var mismatch = Record("Success") with { NominalStart = "2026-10-11T20:05:00Z" };
        Assert.False(QuickTransferCleanupPolicy.CanDelete(Entry(), mismatch, "ADHOC_TEST", false));
    }

    [Fact]
    public void ConfirmationSummary_UsesApprovedHeadingAndFooter()
    {
        var html = QuickTransferCleanupWorker.BuildConfirmationHtml(Entry(), Record("Success"));
        Assert.Contains("Transfer Completed Successfully", html);
        Assert.Contains("This is an automated confirmation generated by MAUI sent from an unattended mailbox.", html);
        Assert.Contains("ADHOC_TEST", html);
        Assert.Contains("Files Transferred", html);
    }

    private static QuickTransferCleanupEntry Entry()
        => new("token", "env", "server", "123", "ADHOC_TEST", Started, "2026-10-11T20:00:00Z");

    private static TaskRunReportRecord Record(string status)
        => new("row", "123", "ADHOC_TEST", Started, Started.AddSeconds(5), 5,
            status, string.Empty, 1, 100d, "admin", "run", null, "2026-10-11T20:00:00Z",
            "1", "0", null, "end", string.Empty);
}
