// Source contracts for compact Quick Transfer options, setting titles and the release-owned import template.
// This is not a browser screenshot, .NET publish, or live MOVEit integration test.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');
const css = read('wwwroot/css/site.css');
const view = read('Views/QuickTransfers/Index.cshtml');
const options = view.match(/<div class="quick-transfer-options-list">([\s\S]*?)<\/section>/)?.[1];
assert.ok(options, 'Task Options section must exist');
assert.equal((options.match(/type="checkbox"/g) || []).length, 2, 'only delete and email checkboxes remain');
assert.doesNotMatch(options, /data-quick-persist-task|data-quick-task-name|data-quick-confirm-recipients-row/);
assert.ok(options.indexOf('data-quick-delete-temp') < options.indexOf('data-quick-confirm-email'));
assert.match(options, /quick-transfer-email-option[\s\S]*data-quick-confirm-email[\s\S]*data-quick-confirm-recipients disabled/);
assert.match(css, /\.quick-transfer-email-option \{[^}]*grid-template-columns:\s*max-content minmax\(0,\s*1fr\)/);
assert.match(css, /max-width:\s*720px[\s\S]*?\.quick-transfer-email-option \{ grid-template-columns: 1fr; \}/);
assert.doesNotMatch(css, /quick-transfer-task-name/);
const settings = read('Views/Configuration/Settings.cshtml');
assert.match(settings, /<strong>Copy Recovery Retention<\/strong>/);
assert.match(settings, /<strong>Create Top-Level Folders from Resource Group Names<\/strong>/);
assert.doesNotMatch(settings, /Copy recovery retention|<span>Metadata field<\/span>|<span>Configuration file<\/span>/);
const templateRel = 'Templates/TaskImport/MAUI_ImportTasksTemplate.xlsx';
const template = fs.readFileSync(path.join(root, templateRel));
assert.ok(template.length > 500);
assert.equal(template.readUInt32LE(0), 0x04034b50, 'Template must be a real XLSX ZIP package');
const project = read('MoveItAutomationUI.csproj');
assert.ok(project.includes('<None Update="Templates\\TaskImport\\MAUI_ImportTasksTemplate.xlsx">'));
assert.match(project, /<None Update="Templates\\TaskImport\\MAUI_ImportTasksTemplate.xlsx">[\s\S]*?<CopyToOutputDirectory>PreserveNewest<\/CopyToOutputDirectory>[\s\S]*?<CopyToPublishDirectory>PreserveNewest<\/CopyToPublishDirectory>/);
console.log('PASS compact Quick Transfer options, grouped recipients, consistent setting titles and published XLSX template contract.');
