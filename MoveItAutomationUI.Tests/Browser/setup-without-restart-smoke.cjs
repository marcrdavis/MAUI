// Source-level RC2 safeguards for no-recycle Setup, database binding and restricted IIS configuration.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const setup = read('Services/Configuration/InitialSetupService.cs');
const lifecycle = read('Services/Configuration/MauiSetupState.cs');
const startup = read('Services/Configuration/ConfigurationStartupState.cs');
const upgrade = read('Services/Upgrade/MauiUpgradeStartupService.cs');
const app = read('Program.cs');
const controller = read('Controllers/SetupController.cs');
const client = read('wwwroot/js/setup.js');
const gate = read('Services/Lifecycle/InitialSetupAccessMiddleware.cs');
const scheduler = read('Services/SystemJobs/SystemJobScheduler.cs');
const report = read('Services/Configuration/AppSettingsDocumentStore.cs');
assert.match(setup, /WriteLiveAsync\(root, cancellationToken\)/);
// Centralized document publication happens as part of WriteLiveAsync, before startup activation.
assert.match(report, /if \(publishRuntime\) _runtimeConfiguration\.Reload\(\)/);
assert.doesNotMatch(setup, /configurationRoot\.Reload\(\)/);
assert.ok(setup.indexOf('WriteLiveAsync(root, cancellationToken)') < setup.indexOf('_runtimeConfiguration.ActivateAfterInitialSetup'));
assert.ok(setup.indexOf('await startup.InitializeAsync(') < setup.indexOf('_setupState.MarkConfigured()'));
assert.match(setup, /afterInitialSetup: true/);
assert.match(setup, /CancellationToken.None, afterInitialSetup: true/);
assert.doesNotMatch(setup, /MarkPendingRestart|ScheduleRestart|StopApplication\(/);
assert.match(setup, /RestartRequired = false/);
assert.match(lifecycle, /Interlocked.Exchange\(ref _isConfigured, 1\)/);
assert.match(lifecycle, /Volatile.Read\(ref _isConfigured\)/);
assert.match(startup, /Volatile.Write\(ref _effective, ReadSnapshot\(configuration\)\)/);
assert.match(app, /configurationStartupState.DatabaseProvider/);
assert.match(app, /configurationStartupState.DatabaseConnectionString/);
assert.match(app, /configurationStartupState.AllowInvalidServerCertificates/);
assert.doesNotMatch(app, /metadataOptions.Provider.Value/);
assert.match(upgrade, /afterInitialSetup/);
assert.match(controller, /loginUrl = Url.Action\("Login", "Account"\)/);
assert.match(client, /window.location.assign\(result\?\.loginUrl/);
assert.match(gate, /HttpMethods.IsGet\(context.Request.Method\)/);
assert.match(scheduler, /_setupState.IsConfiguredAtStartup && !_upgradeState.IsPending/);
assert.match(report, /FileMode.Open, FileAccess.Write, FileShare.None/);
assert.ok(!read('Views/Setup/Index.cshtml').includes('Check After Restart'));
assert.equal(read('appsettings.json').trim(), '{}');
assert.match(read('Services/MoveIt/MoveItSessionService.cs'), /ConfigurationStartupState configuration/);
assert.match(read('Services/MoveIt/MoveItRestClient.cs'), /ConfigurationStartupState configuration/);
assert.match(read('Services/Authentication/MauiApplicationSessionService.cs'), /ConfigurationStartupState runtimeConfiguration/);
assert.match(read('Services/MoveIt/TaskFailureAlertService.cs'), /ConfigurationStartupState runtimeConfiguration/);
assert.match(read('Views/Shared/_Layout.cshtml'), /isPublicShell \? null : Context.RequestServices.GetRequiredService<IMoveItSessionService>\(\)/);
assert.doesNotMatch(read('Views/_ViewImports.cshtml'), /@inject IMoveItSessionService MoveItSessionService/);
assert.doesNotMatch(read('Services/Lifecycle/UpgradeAccessMiddleware.cs'), /IMauiApplicationSessionService applicationSession\)/);
console.log('PASS: RC2 no-restart Initial Setup runtime and IIS configuration contracts');
