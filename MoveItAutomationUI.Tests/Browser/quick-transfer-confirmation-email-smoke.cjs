// Execute the production conditional controls for SMTP, checkbox, busy and running states.
const vm = require('node:vm');
const conditional = js.slice(js.indexOf('    function syncConditionalControls()'), js.indexOf('    function clearPreparedTransfer()'));
for (const available of [true, false]) for (const checked of [true, false]) for (const locked of [true, false]) {
    const recipients = { disabled: false, value: 'person@example.com' }, checkbox = { checked, disabled: false }, deletion = { checked: false };
    const c = { cfg: { confirmationEmailAvailable: String(available) }, busy: locked, transferInProgress: false,
        syncPgpLicenseState() {}, currentMode: () => 'none', pgpRow: null, deleteTemp: deletion,
        confirmationCheckbox: checkbox, confirmationRecipients: recipients, sourceHost: null, destinationHost: null, root: { querySelector: () => null } };
    vm.runInNewContext(conditional + '; syncConditionalControls();', c);
    assert.equal(recipients.disabled, locked || !available || !checked);
    assert.equal(checkbox.disabled, locked || !available);
    assert.equal(deletion.checked, false, 'control synchronization must preserve the unchecked retention choice');
    assert.equal(recipients.value, 'person@example.com', 'unchecking email preserves the draft recipients');
}
