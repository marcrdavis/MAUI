// Source-level regression guard for restart-free MOVEit server configuration.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const catalog = read('Services/Configuration/MoveItServerCatalog.cs');
const rest = read('Services/MoveIt/MoveItRestClient.cs');
const cred = read('Services/MoveIt/DataAccessCredentialService.cs');
const login = read('Controllers/AccountController.cs');
const backup = read('Services/Backup/MauiBackupService.cs');
const health = read('Services/SystemJobs/HostHealthCheckJob.cs');
const readiness = read('Controllers/ConfigurationController.cs');
const restart = read('Services/Configuration/ConfigurationRestartDetector.cs');
const settings = read('Views/Configuration/Settings.cshtml');
const save = read('Services/Configuration/AppSettingsConfigurationService.cs');
assert.match(catalog, /IReadOnlyList<MoveItServerDefinition> GetServers\(\)/);
assert.match(catalog, /_configuration\.GetSection\(MoveItOptions\.SectionName\)/);
assert.match(read('Program.cs'), /AddSingleton<IMoveItServerCatalog, MoveItServerCatalog>/);
assert.match(rest, /_servers\.FindForLogin\(serverKey\)/);
assert.match(login, /_servers\.GetServers\(\)/);
assert.match(cred, /_servers\.FindByKey\(serverKey\)/);
assert.doesNotMatch(cred, /_startupState\.Servers/);
assert.match(backup, /_servers\.GetServers\(\)/);
assert.match(health, /_servers\.GetServers\(\)/);
assert.match(readiness, /_servers\.GetServers\(\)/);
assert.doesNotMatch(restart, /MOVEit server configuration changed/);
assert.match(restart, /Server certificate validation behavior changed/);
assert.match(restart, /Metadata database configuration changed/);
assert.match(settings, /Server changes apply after Save/);
assert.doesNotMatch(settings, /Server changes require restart/);
assert.match(save, /_snapshots\.FromDocument\(root\)/);
assert.match(read('Services/Configuration/AppSettingsDocumentStore.cs'), /_runtimeConfiguration\.Reload\(\)/);
assert.doesNotMatch(save, /configurationRoot\.Reload\(\)/);
assert.match(read('Services/Configuration/ConfigurationSettingsMutator.cs'), /SameConnectionIdentity\(existing, server\)/);
assert.match(read('Services/Configuration/ConfigurationSettingsMutator.cs'), /MoveItEnvironmentKey\.Normalize\(string\.IsNullOrWhiteSpace\(updated\.EnvironmentKey\) \? updated\.Key : updated\.EnvironmentKey\)/);
assert.doesNotMatch(read('Services/Configuration/ConfigurationSettingsMutator.cs'), /MoveItEnvironmentKey\.Resolve\(updated\)/);
assert.match(read('Services/Configuration/ConfigurationSettingsMutator.cs'), /ClearedDataAccessServerKeys = clearedDataAccessServerKeys/);
assert.match(read('wwwroot/js/configuration.js'), /clearedDataAccessServerKeys/);

const releaseVersion = JSON.parse(read('upgrade.json')).TargetVersion;
assert.ok(read('MoveItAutomationUI.csproj').includes(`<Version>${releaseVersion}</Version>`), 'Project and upgrade manifest versions must match');
console.log('MOVEit live server catalog and restart boundaries: PASS');
